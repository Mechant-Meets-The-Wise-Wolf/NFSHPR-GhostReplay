  public static string Format(string key,params object[] args){return args.Length==0?Get(key):string.Format(CultureInfo.InvariantCulture,Get(key),args);}
  public static void Set(Control control,string key,params object[] args){control.Tag=new Binding{Key=key,Args=args};control.Text=Format(key,args);}
  // Replay names, author names and event labels are user data, never translation keys.
  public static void Literal(Control control,string text){control.Tag=null;control.Text=text;}
  public static void Apply(Control root){var binding=root.Tag as Binding;if(binding!=null)root.Text=Format(binding.Key,binding.Args);foreach(Control child in root.Controls)Apply(child);}
